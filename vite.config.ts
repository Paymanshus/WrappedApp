import { defineConfig, type Plugin } from 'vite'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'
import { createHash } from 'node:crypto'
import { readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

/**
 * Content-Security-Policy for production builds. connect-src is the privacy boundary: the page
 * can talk to itself, to model servers on this machine (Ollama, LM Studio…), and to the four AI
 * APIs Ask supports — and nothing else. Those APIs are only called after the user picks one and
 * pastes their own key (lib/agent). Adding an origin here is the visible, reviewable change to
 * "what can leave the device". Dev skips this (Vite's HMR needs inline scripts + websockets).
 */
const ASK_ORIGINS = [
  'http://localhost:*', 'http://127.0.0.1:*',     // Ollama, LM Studio, llama.cpp… on this device
  'https://api.anthropic.com', 'https://api.openai.com',
  'https://generativelanguage.googleapis.com', 'https://openrouter.ai',
]
const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' blob: data:",
  "media-src 'self' blob:",
  "font-src 'self'",
  `connect-src 'self' ${ASK_ORIGINS.join(' ')}`,
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
].join('; ')

function csp(): Plugin {
  return {
    name: 'wrappedapp:csp',
    apply: 'build',
    transformIndexHtml: () => [{ tag: 'meta', attrs: { 'http-equiv': 'Content-Security-Policy', content: CSP }, injectTo: 'head-prepend' }],
  }
}

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap(f => {
    const p = join(dir, f)
    return statSync(p).isDirectory() ? listFiles(p) : [p]
  })
}

/** Emits sw.js: precaches the whole app (hashed bundle + public assets) so it runs offline. */
function offlineServiceWorker(): Plugin {
  return {
    name: 'wrappedapp:sw',
    apply: 'build',
    generateBundle(_, bundle) {
      const pub = listFiles('public').map(p => ({ url: '/' + relative('public', p).split('\\').join('/'), size: statSync(p).size }))
      const assets = ['/', ...Object.keys(bundle).filter(f => f !== 'index.html').map(f => '/' + f), ...pub.map(p => p.url)]
      const version = createHash('sha256').update(JSON.stringify([assets, pub])).digest('hex').slice(0, 12)
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: `// generated by vite.config.ts — precache everything, serve cache-first, never touch other origins
const CACHE = 'wrappedapp-${version}'
const ASSETS = ${JSON.stringify(assets)}
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting()))
})
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('wrappedapp-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()))
})
self.addEventListener('fetch', e => {
  const req = e.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)
  if (url.origin !== self.location.origin) return
  // ignoreVary: hosts send Vary: Origin/Accept-Encoding, and module scripts carry an Origin
  // header the precache requests didn't — without this, offline loads miss the cache
  if (req.mode === 'navigate') {
    e.respondWith(caches.match('/', { ignoreVary: true }).then(hit => hit || fetch(req)))
    return
  }
  e.respondWith(caches.match(req, { ignoreVary: true }).then(hit => hit || fetch(req)))
})
`,
      })
    },
  }
}

export default defineConfig({
  plugins: [react(), tailwindcss(), csp(), offlineServiceWorker()],
  server: { port: Number(process.env.PORT) || 5173 },
  preview: { port: Number(process.env.PORT) || 4173 },
  worker: { format: 'es' },
})
